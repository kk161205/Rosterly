import React, { useEffect, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { getErrorMessage, getFieldErrors } from '@/lib/errors'
import { assetService } from '@/features/assets/services/assetService'
import { useAssetMeta, useRefreshAssets } from '@/features/assets/hooks/useAssets'
import type { Asset, DepreciationMethod } from '@/features/assets/types/assets'
import { Alert, Button, Dialog, SelectField, TextField } from '@/ui'
import { humanize } from '@/lib/format'

/**
 * Add an asset (POST /assets, §5.7) or edit one (PATCH /assets/{id}). The tag
 * is generated by the server. Category offers the ones in use plus a new one.
 */
interface FormState {
  name: string
  category: string
  newCategory: string
  serial_number: string
  vendor: string
  purchase_date: string
  purchase_cost: string
  depreciation_method: DepreciationMethod
  useful_life_months: string
  warranty_expiry: string
  amc_expiry: string
}

const NEW_CATEGORY = '__new__'

const empty: FormState = {
  name: '',
  category: '',
  newCategory: '',
  serial_number: '',
  vendor: '',
  purchase_date: '',
  purchase_cost: '',
  depreciation_method: 'straight_line',
  useful_life_months: '36',
  warranty_expiry: '',
  amc_expiry: '',
}

function fromAsset(a: Asset): FormState {
  return {
    name: a.name,
    category: a.category,
    newCategory: '',
    serial_number: a.serial_number ?? '',
    vendor: a.vendor,
    purchase_date: a.purchase_date,
    purchase_cost: String(Number(a.purchase_cost)),
    depreciation_method: a.depreciation_method,
    useful_life_months: String(a.useful_life_months),
    warranty_expiry: a.warranty_expiry ?? '',
    amc_expiry: a.amc_expiry ?? '',
  }
}

const METHODS: { value: DepreciationMethod; label: string }[] = [
  { value: 'straight_line', label: 'Straight line' },
  { value: 'declining_balance', label: 'Declining balance (20% a year)' },
  { value: 'none', label: 'None' },
]

export const AssetFormDialog: React.FC<{
  open: boolean
  onOpenChange: (open: boolean) => void
  asset?: Asset
}> = ({ open, onOpenChange, asset }) => {
  const navigate = useNavigate()
  const refresh = useRefreshAssets()
  const meta = useAssetMeta()
  const [form, setForm] = useState<FormState>(empty)
  const [errors, setErrors] = useState<Record<string, string>>({})
  const [error, setError] = useState<string | null>(null)
  const [busy, setBusy] = useState(false)

  useEffect(() => {
    if (open) {
      setForm(asset ? fromAsset(asset) : empty)
      setErrors({})
      setError(null)
    }
  }, [open, asset])

  const set = (key: keyof FormState) => (e: React.ChangeEvent<HTMLInputElement | HTMLSelectElement>) =>
    setForm((f) => ({ ...f, [key]: e.target.value }))

  const categories = meta.data?.categories ?? []
  const categoryOptions = [
    ...categories.map((c) => ({ value: c, label: humanize(c) })),
    ...(form.category && form.category !== NEW_CATEGORY && !categories.includes(form.category)
      ? [{ value: form.category, label: humanize(form.category) }]
      : []),
    { value: NEW_CATEGORY, label: 'New category…' },
  ]

  const validate = (): Record<string, string> => {
    const e: Record<string, string> = {}
    if (!form.name.trim()) e.name = 'Enter a name.'
    const category = form.category === NEW_CATEGORY ? form.newCategory.trim() : form.category
    if (!category) e.category = 'Choose or add a category.'
    if (!form.vendor.trim()) e.vendor = 'Enter the vendor.'
    if (!form.purchase_date) e.purchase_date = 'Enter the purchase date.'
    if (form.purchase_cost === '' || Number(form.purchase_cost) < 0) e.purchase_cost = 'Enter a cost of ₹0 or more.'
    if (!(Number(form.useful_life_months) > 0)) e.useful_life_months = 'Enter at least 1 month.'
    return e
  }

  const save = async () => {
    const v = validate()
    setErrors(v)
    if (Object.keys(v).length) return
    setBusy(true)
    setError(null)
    const payload = {
      name: form.name.trim(),
      category: form.category === NEW_CATEGORY ? form.newCategory.trim().toLowerCase() : form.category,
      serial_number: form.serial_number.trim() || null,
      vendor: form.vendor.trim(),
      purchase_date: form.purchase_date,
      purchase_cost: Number(form.purchase_cost),
      depreciation_method: form.depreciation_method,
      useful_life_months: Number(form.useful_life_months),
      warranty_expiry: form.warranty_expiry || null,
      amc_expiry: form.amc_expiry || null,
    }
    try {
      if (asset) {
        await assetService.updateAsset(asset.id, payload)
        await refresh()
        onOpenChange(false)
      } else {
        const created = await assetService.createAsset(payload)
        await refresh()
        onOpenChange(false)
        navigate(`/assets/${created.id}`)
      }
    } catch (err) {
      setError(getErrorMessage(err))
      setErrors(getFieldErrors(err))
    } finally {
      setBusy(false)
    }
  }

  return (
    <Dialog
      open={open}
      onOpenChange={onOpenChange}
      title={asset ? 'Edit details' : 'Add an asset'}
      description={asset ? `${asset.name} · ${asset.asset_tag}` : 'The asset tag is created when you save.'}
      className="max-w-2xl"
      footer={
        <>
          <Button variant="ghost" onClick={() => onOpenChange(false)} disabled={busy}>
            Cancel
          </Button>
          <Button variant="primary" isLoading={busy} onClick={save}>
            {asset ? 'Save changes' : 'Add asset'}
          </Button>
        </>
      }
    >
      <div className="flex flex-col gap-5">
        {error && <Alert>{error}</Alert>}
        <TextField label="Name" value={form.name} onChange={set('name')} error={errors.name} placeholder="e.g. MacBook Air M2" />
        <div className="grid gap-5 sm:grid-cols-2">
          <SelectField
            label="Category"
            placeholder="Choose a category"
            options={categoryOptions}
            value={form.category}
            onChange={set('category')}
            error={form.category === NEW_CATEGORY ? undefined : errors.category}
          />
          {form.category === NEW_CATEGORY ? (
            <TextField
              label="New category"
              value={form.newCategory}
              onChange={set('newCategory')}
              error={errors.category}
              autoFocus
            />
          ) : (
            <TextField label="Serial number" value={form.serial_number} onChange={set('serial_number')} error={errors.serial_number} />
          )}
          {form.category === NEW_CATEGORY && (
            <TextField label="Serial number" value={form.serial_number} onChange={set('serial_number')} error={errors.serial_number} />
          )}
          <TextField label="Vendor" value={form.vendor} onChange={set('vendor')} error={errors.vendor} />
          <TextField label="Purchase date" type="date" value={form.purchase_date} onChange={set('purchase_date')} error={errors.purchase_date} />
          <TextField
            label="Purchase cost (₹)"
            type="number"
            inputMode="decimal"
            min={0}
            value={form.purchase_cost}
            onChange={set('purchase_cost')}
            error={errors.purchase_cost}
          />
          <SelectField
            label="Depreciation"
            options={METHODS}
            value={form.depreciation_method}
            onChange={set('depreciation_method')}
            error={errors.depreciation_method}
          />
          <TextField
            label="Useful life (months)"
            type="number"
            min={1}
            value={form.useful_life_months}
            onChange={set('useful_life_months')}
            error={errors.useful_life_months}
          />
          <TextField label="Warranty ends" type="date" value={form.warranty_expiry} onChange={set('warranty_expiry')} error={errors.warranty_expiry} />
          <TextField label="AMC ends" type="date" value={form.amc_expiry} onChange={set('amc_expiry')} error={errors.amc_expiry} />
        </div>
      </div>
    </Dialog>
  )
}
